using System.Collections.Generic;
using NUnit.Framework;
using Warpaz.Application;
using Warpaz.Domain;

namespace Warpaz.Tests.EditMode
{
    /// <summary>
    /// Golden test: executes a pinned seed + command sequence and asserts the exact
    /// final hash, phase sequence, PA-max progression and hand/deck sizes.
    ///
    /// The expected values below correspond to Sprint1GoldenFixture.json in StreamingAssets/Tests/.
    /// Update both files together if the engine spec changes intentionally.
    ///
    /// Does not include timestamps or absolute paths.
    /// </summary>
    public sealed class Sprint1GoldenTest
    {
        // ------------------------------------------------------------------ pinned constants
        // Derived from Sprint1GoldenFixture.json (seed=42, both mulligans KeepHand, 5 EndTurns).
        // Generated by running the engine once and recording the output.

        private const ulong Seed = 42UL;
        private const string ContentVersion = "WZ1-v0.1";
        private const string RuleVersion = "0.1.0";

        private const string Player0HeroId  = "WZ1-001";
        private const string Player0ClassId = "WZ1-012";
        private const string Player1HeroId  = "WZ1-002";
        private const string Player1ClassId = "WZ1-013";

        private const string ExpectedFinalHash = "64dd38329bc1485db3a05380afc4f5d52d1adcc5aacfde72b49c78abca081ff4";

        private static readonly string[] ExpectedPhaseSequence =
        {
            "MulliganP0", "MulliganP1", "Main",
            "Main", "Main", "Main", "Main", "Main"
        };

        /// <summary>PA-max for the active player recorded right after entering Main and after each EndTurn.</summary>
        private static readonly int[] ExpectedPaMaxByTurn = { 1, 1, 2, 2, 3, 3 };

        private const int ExpectedHandSizeAfterBothMulligans = 6;
        private const int ExpectedDeckSizeAfterBothMulligans = 34;

        // ------------------------------------------------------------------ test

        [Test]
        public void Sprint1_GoldenFixture_ProducesExpectedOutput()
        {
            var catalog = Wz1MatchFixtures.Catalog;

            // Verify that the catalog and rules still match what the fixture was generated with.
            Assert.AreEqual(ContentVersion, catalog.ContentVersion,
                "Catalog contentVersion changed — regenerate the golden fixture");
            Assert.AreEqual(RuleVersion, RuleConfig.AlphaRuleVersion,
                "AlphaRuleVersion changed — regenerate the golden fixture");

            // Build MatchSetup from pinned IDs (not from names).
            var heroId0  = new CardId(Player0HeroId);
            var classId0 = new CardId(Player0ClassId);
            var heroId1  = new CardId(Player1HeroId);
            var classId1 = new CardId(Player1ClassId);

            Assert.IsTrue(catalog.TryGet(heroId0,  out _), "player0HeroId not in catalog");
            Assert.IsTrue(catalog.TryGet(classId0, out _), "player0ClassId not in catalog");
            Assert.IsTrue(catalog.TryGet(heroId1,  out _), "player1HeroId not in catalog");
            Assert.IsTrue(catalog.TryGet(classId1, out _), "player1ClassId not in catalog");

            var setup = new MatchSetup(
                Seed,
                RuleConfig.AlphaDefaults(),
                catalog.ContentVersion,
                new PlayerSetup(PlayerId.Player0, heroId0, classId0, Wz1MatchFixtures.MainDeck40()),
                new PlayerSetup(PlayerId.Player1, heroId1, classId1, Wz1MatchFixtures.MainDeck40()));

            var session = new GameSession(catalog);
            var startResult = session.Start(setup);
            Assert.IsTrue(startResult.Accepted, "Start rejected: " + startResult.RejectionReason);

            // Track phase sequence and PA-max per command checkpoint.
            var phaseSequence = new List<string> { session.State.Phase.ToString() };
            var paMaxByTurn = new List<int>();

            // ConfirmMulligan for both players (KeepHand).
            var m0 = session.ConfirmMulligan(PlayerId.Player0, MulliganDecision.KeepHand);
            Assert.IsTrue(m0.Accepted, "ConfirmMulligan P0 rejected: " + m0.RejectionReason);
            phaseSequence.Add(session.State.Phase.ToString());

            var m1 = session.ConfirmMulligan(PlayerId.Player1, MulliganDecision.KeepHand);
            Assert.IsTrue(m1.Accepted, "ConfirmMulligan P1 rejected: " + m1.RejectionReason);
            phaseSequence.Add(session.State.Phase.ToString());

            // Verify hand / deck sizes for the active player right after both mulligans.
            var activePlayer = session.State.ActivePlayerId;
            Assert.AreEqual(ExpectedHandSizeAfterBothMulligans,
                session.State.GetPlayer(activePlayer).HandInstanceIds.Count,
                "Hand size after both mulligans does not match golden fixture");
            Assert.AreEqual(ExpectedDeckSizeAfterBothMulligans,
                session.State.GetPlayer(activePlayer).DeckInstanceIds.Count,
                "Deck size after both mulligans does not match golden fixture");

            // Record PA-max entering Main.
            paMaxByTurn.Add(session.State.GetPlayer(session.State.ActivePlayerId).PaMax);

            // Execute 5 EndTurn commands.
            for (var i = 0; i < 5; i++)
            {
                var r = session.EndTurn(session.State.ActivePlayerId);
                Assert.IsTrue(r.Accepted, "EndTurn " + (i + 1) + " rejected: " + r.RejectionReason);
                phaseSequence.Add(session.State.Phase.ToString());
                paMaxByTurn.Add(session.State.GetPlayer(session.State.ActivePlayerId).PaMax);
            }

            // 1. Verify final hash.
            var finalHash = GameStateHasher.Hash(session.State);
            Assert.AreEqual(ExpectedFinalHash, finalHash,
                "Final hash does not match pinned value — engine behaviour changed");

            // 2. Verify phase sequence.
            Assert.AreEqual(ExpectedPhaseSequence.Length, phaseSequence.Count,
                "Phase sequence length differs from golden fixture");
            for (var i = 0; i < ExpectedPhaseSequence.Length; i++)
            {
                Assert.AreEqual(ExpectedPhaseSequence[i], phaseSequence[i],
                    "Phase at step " + i + " differs from golden fixture");
            }

            // 3. Verify PA-max progression.
            Assert.AreEqual(ExpectedPaMaxByTurn.Length, paMaxByTurn.Count,
                "PA-max sequence length differs from golden fixture");
            for (var i = 0; i < ExpectedPaMaxByTurn.Length; i++)
            {
                Assert.AreEqual(ExpectedPaMaxByTurn[i], paMaxByTurn[i],
                    "PaMax at step " + i + " differs from golden fixture");
            }
        }
    }
}
